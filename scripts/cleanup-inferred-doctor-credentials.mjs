import mongoose from "mongoose";

const EXCLUDED_SLUGS = new Set([
  "dr-pranendra-singh",
  "hair-transplant-doctor-in-delhi",
  "hair-transplant-doctor-in-chennai",
  "hair-transplant-doctor-in-gurgaon",
]);

async function main() {
  const isDryRun = process.argv.includes("--dry-run");
  const uri = process.env.MONGO_URL;
  if (!uri) {
    console.error("MONGO_URL not found in environment");
    process.exit(1);
  }

  console.log(`Connecting to MongoDB... (Mode: ${isDryRun ? "DRY-RUN (no database writes)" : "LIVE EXECUTION"})`);
  await mongoose.connect(uri);
  const collection = mongoose.connection.db.collection("doctors");

  const doctors = await collection.find({}).toArray();
  console.log(`Auditing ${doctors.length} total doctor records.\n`);

  let modifiedCount = 0;
  const auditLog = [];

  for (const doc of doctors) {
    const slug = doc.slug;
    const docName = doc.basicInfo?.doctorName || "Unknown Doctor";
    const city = doc.basicInfo?.city || "Unknown City";

    // 1. SAFETY: Never touch Dr. Pranendra Singh records
    if (EXCLUDED_SLUGS.has(slug) || docName.toLowerCase().includes("pranendra")) {
      console.log(`[PRESERVED] ${slug} (${docName}, ${city}): Legitimate Dr. Pranendra Singh credentials preserved untouched.`);
      continue;
    }

    const updates = {};
    const changes = [];

    // Ensure doctor-specific credentials.cardHeading
    if (!doc.credentials?.cardHeading || doc.credentials.cardHeading.trim() === "") {
      const newVal = `Credentials & Professional Qualifications — ${docName}`;
      updates["credentials.cardHeading"] = newVal;
      changes.push({
        field: "credentials.cardHeading",
        oldValue: doc.credentials?.cardHeading || null,
        newValue: newVal,
        reason: "Populate doctor-specific cardHeading",
      });
    }

    // 2. keyFacts.registration
    const currentReg = doc.keyFacts?.registration;
    if (currentReg && currentReg.startsWith("Registered Medical Council")) {
      const newVal = "Verification pending";
      updates["keyFacts.registration"] = newVal;
      changes.push({
        field: "keyFacts.registration",
        oldValue: currentReg,
        newValue: newVal,
        reason: "Inferred city-based council text from migration script line 183; not a verified registration",
      });
    }

    // 3. keyFacts.memberships
    const currentMem = doc.keyFacts?.memberships;
    if (currentMem && currentMem.includes("Medical Council Registered")) {
      const newVal = "Verification pending";
      updates["keyFacts.memberships"] = newVal;
      changes.push({
        field: "keyFacts.memberships",
        oldValue: currentMem,
        newValue: newVal,
        reason: "Inferred city-based membership claim from migration script line 186; not verified",
      });
    }

    // 4. keyFacts.qualifications (only clean if cloned MBBS, MS, MCh from Dr. Pranendra)
    const currentQual = doc.keyFacts?.qualifications;
    if (currentQual === "MBBS, MS, MCh (Plastic Surgery)") {
      const newVal = "";
      updates["keyFacts.qualifications"] = newVal;
      changes.push({
        field: "keyFacts.qualifications",
        oldValue: currentQual,
        newValue: newVal,
        reason: "Cloned from Dr. Pranendra Singh; authentic qualification for this doctor is unverified",
      });
    }

    // 5. surgeonProfile.achievements
    const existingAchievements = doc.surgeonProfile?.achievements || [];
    let achChanged = false;
    const filteredAchievements = existingAchievements.filter((ach) => {
      // Remove migration-generated "council-reg"
      if (ach.key === "council-reg" || (ach.title === "State Medical Council" && (ach.description || "").includes("licensure in"))) {
        achChanged = true;
        changes.push({
          field: "surgeonProfile.achievements[]",
          oldValue: `${ach.title}: ${ach.description}`,
          newValue: "[REMOVED]",
          reason: "Unverified council registration achievement generated by migration script line 167",
        });
        return false;
      }
      // Remove cloned "MCh (Plastic Surgery)" achievement on non-Delhi doctors
      if (ach.title === "MCh (Plastic Surgery)" && (ach.description || "").includes("Advanced specialization in cosmetic")) {
        achChanged = true;
        changes.push({
          field: "surgeonProfile.achievements[]",
          oldValue: `${ach.title}: ${ach.description}`,
          newValue: "[REMOVED]",
          reason: "Cloned plastic surgery qualification achievement from Dr. Pranendra Singh",
        });
        return false;
      }
      return true;
    });

    if (achChanged) {
      updates["surgeonProfile.achievements"] = filteredAchievements;
    }

    // 6. credentials.tabs council tab description
    const existingTabs = doc.credentials?.tabs || [];
    let tabsChanged = false;
    const updatedTabs = existingTabs.map((tab) => {
      const t = { ...tab };
      const desc = t.description || "";
      if (desc.includes("Active statutory registration with state medical council verifying legal practice and surgical licensure in")) {
        const oldDesc = desc;
        t.description = "Registration details available upon request. Verification pending official council records.";
        tabsChanged = true;
        changes.push({
          field: `credentials.tabs[title="${t.title}"].description`,
          oldValue: oldDesc,
          newValue: t.description,
          reason: "Inferred council registration description generated by migration script line 76",
        });
      }
      return t;
    });

    if (tabsChanged) {
      updates["credentials.tabs"] = updatedTabs;
    }

    // 7. verification.checklist[0] city neutralization
    const existingChecklist = doc.verification?.checklist || [];
    let checklistChanged = false;
    const updatedChecklist = existingChecklist.map((item) => {
      const it = { ...item };
      if (it.title && it.title.startsWith("Verify ") && it.title.includes("state medical council registration on official online register")) {
        const oldTitle = it.title;
        it.title = "Verify state medical council registration on official online register";
        if (oldTitle !== it.title) {
          checklistChanged = true;
          changes.push({
            field: `verification.checklist[key="${it.key}"].title`,
            oldValue: oldTitle,
            newValue: it.title,
            reason: "Inferred city-specific checklist title generated by migration script line 119",
          });
        }
      }
      return it;
    });

    if (checklistChanged) {
      updates["verification.checklist"] = updatedChecklist;
    }

    // 8. surgeonProfile.heading isolation (no Dr. Pranendra Singh on other doctors)
    if (doc.surgeonProfile?.heading && doc.surgeonProfile.heading.includes("Dr. Pranendra Singh")) {
      const oldHeading = doc.surgeonProfile.heading;
      const newHeading = oldHeading.replace(/Dr\.\s*Pranendra\s*Singh/gi, docName);
      updates["surgeonProfile.heading"] = newHeading;
      changes.push({
        field: "surgeonProfile.heading",
        oldValue: oldHeading,
        newValue: newHeading,
        reason: "Cloned Dr. Pranendra Singh name on different doctor's profile heading",
      });
    }

    // 9. questionsToAsk isolation (no Dr. Pranendra Singh or DMC-68492 on non-Delhi doctors)
    const existingQuestions = doc.questionsToAsk?.questions || [];
    let qChanged = false;
    const updatedQuestions = existingQuestions.map((q) => {
      let itemUpdated = false;
      const newQ = { ...q };
      if (newQ.question && newQ.question.includes("DMC")) {
        newQ.question = newQ.question.replace(/DMC\s*\/\s*NMC/g, "State Medical Council / NMC");
        itemUpdated = true;
      }
      if (newQ.ryanStandard) {
        let rs = newQ.ryanStandard;
        if (rs.includes("Dr. Pranendra Singh")) {
          rs = rs.replace(/Dr\.\s*Pranendra\s*Singh/gi, docName);
          itemUpdated = true;
        }
        if (rs.includes("(DMC-68492)") || rs.includes("DMC-68492")) {
          rs = rs.replace(/\s*\(DMC-68492\)/g, "").replace(/DMC-68492/g, "");
          itemUpdated = true;
        }
        if (rs.includes("DMC")) {
          rs = rs.replace(/DMC/g, "State Medical Council");
          itemUpdated = true;
        }
        if (itemUpdated) {
          newQ.ryanStandard = rs.trim();
        }
      }
      if (itemUpdated) {
        qChanged = true;
        changes.push({
          field: `questionsToAsk.questions[key="${q.key || q.question?.slice(0, 20)}"]`,
          oldValue: `${q.question} -> ${q.ryanStandard}`,
          newValue: `${newQ.question} -> ${newQ.ryanStandard}`,
          reason: "Cloned Dr. Pranendra Singh or DMC credential claim in questionsToAsk",
        });
      }
      return newQ;
    });

    if (qChanged) {
      updates["questionsToAsk.questions"] = updatedQuestions;
    }

    // 10. consultation.contactCards isolation (no Pitampura address on non-Delhi doctors)
    const existingCards = doc.consultation?.contactCards || [];
    let cardsChanged = false;
    const updatedCards = existingCards.map((card) => {
      const c = { ...card };
      if ((c.value && c.value.includes("Pitampura")) || (c.link && c.link.includes("Pitampura"))) {
        const oldVal = `${c.value} | ${c.link}`;
        c.value = doc.basicInfo?.clinicAddress || (city ? `Ryan Clinic, ${city}` : "Ryan Clinic");
        c.link = `https://maps.google.com/?q=${encodeURIComponent(c.value)}`;
        cardsChanged = true;
        changes.push({
          field: `consultation.contactCards[title="${c.title}"]`,
          oldValue: oldVal,
          newValue: `${c.value} | ${c.link}`,
          reason: "Cloned Pitampura Delhi address in consultation contactCards on non-Delhi doctor",
        });
      }
      return c;
    });

    if (cardsChanged) {
      updates["consultation.contactCards"] = updatedCards;
    }

    // 11. faq.faqs isolation (no DMC references in non-Delhi doctor FAQs)
    const existingFaqs = doc.faq?.faqs || [];
    let faqsChanged = false;
    const updatedFaqs = existingFaqs.map((faq) => {
      let fUpdated = false;
      const newF = { ...faq };
      if (newF.answer && (newF.answer.includes("DMC") || newF.answer.includes("Pitampura"))) {
        const oldAnswer = newF.answer;
        newF.answer = newF.answer
          .replace(/check their medical council registration\s*\(DMC\)/gi, "check their medical council registration (State Medical Council / NMC)")
          .replace(/such as DMC in\s*([a-zA-Z\s]+)/gi, "such as the State Medical Council in $1")
          .replace(/DMC/g, "State Medical Council");
        if (oldAnswer !== newF.answer) {
          fUpdated = true;
          changes.push({
            field: `faq.faqs[q="${faq.question?.slice(0, 20)}"].answer`,
            oldValue: oldAnswer,
            newValue: newF.answer,
            reason: "DMC reference in non-Delhi doctor FAQ answer",
          });
        }
      }
      if (fUpdated) faqsChanged = true;
      return newF;
    });

    if (faqsChanged) {
      updates["faq.faqs"] = updatedFaqs;
    }

    if (changes.length > 0) {
      modifiedCount++;
      auditLog.push({
        slug,
        docName,
        city,
        changes,
        updates,
      });

      console.log(`[TARGETED] ${slug} (${docName}, ${city}): ${changes.length} unsafe/inferred values identified.`);
      for (const c of changes) {
        console.log(`    - ${c.field}:`);
        console.log(`        OLD: "${c.oldValue}"`);
        console.log(`        NEW: "${c.newValue}"`);
        console.log(`        REASON: ${c.reason}`);
      }

      if (!isDryRun) {
        await collection.updateOne({ _id: doc._id }, { $set: updates });
        console.log(`    -> APPLIED to MongoDB successfully.`);
      }
      console.log("");
    } else {
      console.log(`[CLEAN/ALREADY NEUTRALIZED] ${slug} (${docName}, ${city}): No unverified migration values found.`);
    }
  }

  console.log(`\n============================================================`);
  console.log(`AUDIT & CLEANUP SUMMARY (${isDryRun ? "DRY RUN" : "LIVE EXECUTION"})`);
  console.log(`============================================================`);
  console.log(`Total doctors examined: ${doctors.length}`);
  console.log(`Total preserved (Dr. Pranendra Singh records): ${EXCLUDED_SLUGS.size}`);
  console.log(`Total non-Delhi records targeted: ${modifiedCount}`);
  if (isDryRun) {
    console.log(`Status: DRY-RUN complete. 0 database modifications made.`);
    console.log(`Review above diffs. Run without --dry-run to apply changes.`);
  } else {
    console.log(`Status: SUCCESS. All ${modifiedCount} targeted documents safely updated in MongoDB.`);
  }

  await mongoose.disconnect();
}

main().catch((err) => {
  console.error("Cleanup error:", err);
  process.exit(1);
});
